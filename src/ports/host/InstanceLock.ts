/**
 * 多标签页协调（宿主能力）
 *
 * 【为什么需要它】
 * 数据落在 OPFS 上的一个 SQLite 库里。同一个 origin 打开两个标签页，就是**两个
 * 进程各拿一份连接写同一个库**：SQLite 自身的文件锁能不能在 OPFS 上正确生效，
 * 既不是我们实现的、也没有测试覆盖 —— 换句话说，"同时写会不会坏"这个问题
 * 在应用这一层是**未知**的。
 *
 * 未知就不要装作知道。这里的做法是：用 Web Locks 选举一个"写者"，
 * 让第二实例**知道自己是谁**，界面据此把风险如实告诉用户
 * （见 `ui/components/Notices`）。
 *
 * 【为什么只是"告知"而不是"拦住"】
 * 直接把第二实例挡在门外（拒绝打开数据库）会带来一次明确的体验退化，
 * 而"并发写一定损坏"并没有证据 —— 用一个更糟的确定性去防一个不确定，
 * 不划算。先把身份暴露出来：真要改成"第二实例只读"，只需在这里换策略。
 *
 * 【为什么放在 ports】
 * `AppContainer` 要暴露它，而 ports 不允许 import adapters ——
 * 所以"身份"这个概念本身定义在端口层，适配器负责用 Web Locks 实现。
 */
export type InstanceRole =
  /** 本页持有写者身份（第一个标签页） */
  | 'primary'
  /** 别的标签页已经是写者（本页是后开的） */
  | 'secondary'
  /** 宿主不支持（旧浏览器 / 无 navigator.locks 的环境，例如测试与 SSR） */
  | 'unsupported';

export interface InstanceLock {
  /**
   * 本页在这次会话里的身份
   *
   * 只判定一次并记住结果（锁要一直持有到页面关闭，重复申请没有意义）。
   */
  role(): Promise<InstanceRole>;
}
